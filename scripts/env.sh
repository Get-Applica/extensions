#!/usr/bin/env bash
# Shared APPLICA_ENV helpers for extension build scripts.

resolve_applica_env() {
  case "${APPLICA_ENV:-local}" in
    local|dev|development)
      echo "local"
      ;;
    prod|production)
      echo "production"
      ;;
    *)
      echo "error: unknown APPLICA_ENV='${APPLICA_ENV}' (use local or production)" >&2
      exit 1
      ;;
  esac
}

app_origin_for_env() {
  case "$1" in
    local) echo "http://localhost:4000" ;;
    production) echo "https://app.getapplica.com" ;;
    *)
      echo "error: unknown env '$1'" >&2
      exit 1
      ;;
  esac
}

write_config() {
  local out_dir="$1"
  local env="$2"
  local origin
  origin="$(app_origin_for_env "$env")"

  cat > "$out_dir/lib/config.js" <<EOF
/**
 * Generated by scripts/package.sh (APPLICA_ENV=${env}).
 * Do not edit in dist/ — rebuild with APPLICA_ENV=local or APPLICA_ENV=production.
 */
window.APPLICA_DEFAULT_APP_ORIGIN = '${origin}';
EOF
}

patch_manifest_for_env() {
  local manifest_path="$1"
  local env="$2"

  python3 - "$manifest_path" "$env" <<'PY'
import json
import sys

path, env = sys.argv[1], sys.argv[2]

with open(path, encoding="utf-8") as f:
    manifest = json.load(f)

if env == "production":
    host = "https://app.getapplica.com/*"
    manifest["host_permissions"] = [host]
    for entry in manifest.get("content_scripts", []):
        entry["matches"] = ["https://app.getapplica.com/*"]
else:
    manifest["host_permissions"] = [
        "http://localhost:4000/*",
        "https://*.fly.dev/*",
    ]
    for entry in manifest.get("content_scripts", []):
        entry["matches"] = ["http://localhost:4000/*"]

with open(path, "w", encoding="utf-8") as f:
    json.dump(manifest, f, indent=2)
    f.write("\n")
PY
}

apply_env_to_dist() {
  local out_dir="$1"
  local env="$2"

  write_config "$out_dir" "$env"
  if [[ -f "$out_dir/manifest.json" ]]; then
    patch_manifest_for_env "$out_dir/manifest.json" "$env"
  fi
}
